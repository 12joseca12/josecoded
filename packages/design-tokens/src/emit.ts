import { designSchema } from './schema.ts';

import type { Design } from './schema.ts';

// Pure emission of tokens.css, breakpoints.ts and tokens.ts from design.json (working-agreements §2,
// DT §1.9). No file access here: scripts/build.ts writes, the tests compare.

const HEADER = 'GENERATED by packages/design-tokens from .impeccable/design.json — do not edit';

interface Token {
  name: string; // without the leading `--`
  value: string;
  group: string;
}

function fromRecord(group: string, prefix: string, record: Record<string, string>): Token[] {
  return Object.entries(record).map(([name, value]) => ({
    name: `${prefix}${name}`,
    value,
    group,
  }));
}

function fromEntries(
  group: string,
  prefix: string,
  list: { name: string; value: string }[],
): Token[] {
  return list.map(({ name, value }) => ({ name: `${prefix}${name}`, value, group }));
}

function typographyTokens(design: Design): Token[] {
  const tokens: Token[] = [];
  for (const [role, t] of Object.entries(design.typography)) {
    const base = `font-${role}`;
    tokens.push({ name: `${base}-size`, value: t.fontSize, group: 'typography' });
    if (t.fontWeight !== undefined) {
      tokens.push({ name: `${base}-weight`, value: String(t.fontWeight), group: 'typography' });
    }
    if (t.lineHeight !== undefined) {
      tokens.push({ name: `${base}-leading`, value: String(t.lineHeight), group: 'typography' });
    }
    if (t.letterSpacing !== undefined) {
      tokens.push({ name: `${base}-tracking`, value: t.letterSpacing, group: 'typography' });
    }
    if (t.fontFeature !== undefined) {
      tokens.push({ name: `${base}-features`, value: t.fontFeature, group: 'typography' });
    }
  }
  return tokens;
}

function collect(design: Design): Token[] {
  const x = design.extensions;
  return [
    ...fromRecord('colors', '', design.colors),
    ...fromRecord('fonts', 'font-', design.fontFamilies),
    ...Object.entries(design.fontWeights).map(([name, value]) => ({
      name: `font-${name}-weight`,
      value,
      group: 'fonts',
    })),
    ...typographyTokens(design),
    ...fromRecord('rounded', 'r-', design.rounded),
    ...fromRecord('spacing', 'sp-', design.spacing),
    ...fromRecord('sizes', 'size-', design.sizes),
    ...fromRecord('focus', '', design.focus),
    ...fromRecord('strokes', '', design.strokes),
    ...fromEntries('alphas', '', x.alphas),
    ...fromEntries('shadows', 'shadow-', x.shadows),
    ...fromEntries('blurs', '', x.blurs),
    ...fromEntries('durations', 'dur-', x.durations),
    ...fromEntries('easings', 'ease-', x.easings),
    ...fromEntries('scroll', '', x.scroll),
    ...fromEntries('layers', 'z-', x.layers),
    ...fromEntries('viewport', 'bp-', x.viewport),
    ...fromEntries('containers', 'cq-', x.containers),
    ...fromEntries('gradients', '', x.gradients),
    ...fromEntries('lights', 'light-', x.lights),
    ...fromEntries('geometry', '', x.geometry),
  ];
}

function assertValid(tokens: Token[]) {
  const seen = new Set<string>();
  for (const token of tokens) {
    if (seen.has(token.name)) throw new Error(`design.json: duplicate token --${token.name}`);
    seen.add(token.name);
    if (/[;{}]/.test(token.value)) {
      throw new Error(
        `design.json: --${token.name} contains ';', '{' or '}', which would break the CSS`,
      );
    }
    if (
      (token.group === 'viewport' || token.group === 'containers') &&
      !/^[\d.]+rem$/.test(token.value)
    ) {
      throw new Error(
        `design.json: ${token.group} --${token.name} must be in rem, got ${token.value}`,
      );
    }
  }
}

function cssOf(tokens: Token[]): string {
  const lines = [`/* ${HEADER} */`, ':root {'];
  let current = '';
  for (const token of tokens) {
    if (token.group !== current) {
      if (current !== '') lines.push('');
      lines.push(`  /* ${token.group} */`);
      current = token.group;
    }
    lines.push(`  --${token.name}: ${token.value};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const quote = (key: string) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`);

function breakpointsOf(tokens: Token[]): string {
  const entry = (group: string, prefix: string) =>
    tokens
      .filter((t) => t.group === group)
      .map((t) => `  ${quote(t.name.slice(prefix.length))}: '${t.value}',`);
  return [
    `// ${HEADER}`,
    '// Media queries cannot use var(): breakpoints are also exported for TypeScript.',
    'export const bp = {',
    ...entry('viewport', 'bp-'),
    '} as const;',
    '',
    'export const cq = {',
    ...entry('containers', 'cq-'),
    '} as const;',
    '',
  ].join('\n');
}

function tokensTsOf(tokens: Token[]): string {
  const names = tokens.map((t) => `--${t.name}`);
  return [
    `// ${HEADER}`,
    '/// <reference lib="dom" />',
    '',
    'export type TokenName =',
    ...names.map((n, i) => `  | '${n}'${i === names.length - 1 ? ';' : ''}`),
    '',
    '/** Reads a design token from the document. Motion code reads tokens only through this. */',
    'export function readToken(name: TokenName): string {',
    '  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();',
    '}',
    '',
    'export const tokens = {',
    ...tokens.map((t) => `  ${quote(t.name)}: '--${t.name}',`),
    '} as const satisfies Record<string, TokenName>;',
    '',
  ].join('\n');
}

export function emitTokens(input: unknown): {
  css: string;
  breakpointsTs: string;
  tokensTs: string;
  names: string[];
} {
  const parsed = designSchema.safeParse(input);
  if (!parsed.success) {
    const where = parsed.error.issues.map((i) => i.path.join('.')).join(', ');
    throw new Error(`design.json is invalid at: ${where}`);
  }
  const tokens = collect(parsed.data);
  assertValid(tokens);
  return {
    css: cssOf(tokens),
    breakpointsTs: breakpointsOf(tokens),
    tokensTs: tokensTsOf(tokens),
    names: tokens.map((t) => `--${t.name}`),
  };
}
