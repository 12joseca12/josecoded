import { describe, expect, it } from 'vitest';

import { emitTokens } from '../src/emit.ts';

const minimal = {
  schemaVersion: 2,
  colors: { bg: '#07060f', 'text-2': '#a9a3d6' },
  fontFamilies: { sans: '"Geist", sans-serif', mono: '"Geist Mono", monospace' },
  fontWeights: { emphasis: '500' },
  typography: {
    display: {
      family: 'sans',
      fontSize: 'clamp(3rem, 6.4vw, 5.75rem)',
      fontWeight: 600,
      lineHeight: 0.96,
      letterSpacing: '-0.045em',
    },
    body: { family: 'sans', fontSize: '1rem', fontWeight: 400, fontFeature: '"ss01", "cv11"' },
  },
  rounded: { pill: '9999rem' },
  spacing: { gutter: 'clamp(1rem, 4vw, 3.5rem)', '8': '2rem' },
  sizes: { dot: '0.375rem' },
  focus: { 'focus-ring-width': '2px' },
  strokes: { 'stroke-line': '2px' },
  extensions: {
    alphas: [{ name: 'tint-chip', value: 'rgb(157 140 255 / 0.08)' }],
    shadows: [{ name: 'card', value: 'inset 0 0 0 1px red' }],
    blurs: [
      { name: 'blur-header', value: '14px' },
      { name: 'saturate-header', value: '1.2' },
    ],
    durations: [{ name: 'hover', value: '150ms' }],
    easings: [{ name: 'out', value: 'cubic-bezier(0.23, 1, 0.32, 1)' }],
    scroll: [{ name: 'glide-min', value: '600ms' }],
    layers: [{ name: 'header', value: '30' }],
    viewport: [{ name: 'menu', value: '67.5rem' }],
    containers: [{ name: 'bento-2', value: '34rem' }],
    gradients: [{ name: 'grad-keycap', value: 'linear-gradient(180deg, #1f1a44, #151233)' }],
    lights: [{ name: 'alpha', value: '0.09' }],
  },
};

describe('emitTokens', () => {
  const out = emitTokens(minimal);

  it('writes one :root block with the GENERATED header', () => {
    expect(out.css.startsWith('/* GENERATED by packages/design-tokens')).toBe(true);
    expect(out.css.match(/:root \{/g)).toHaveLength(1);
  });

  it('prefixes by group and keeps kebab-case names', () => {
    for (const line of [
      '--bg: #07060f;',
      '--text-2: #a9a3d6;',
      '--font-sans: "Geist", sans-serif;',
      '--r-pill: 9999rem;',
      '--sp-gutter: clamp(1rem, 4vw, 3.5rem);',
      '--sp-8: 2rem;',
      '--size-dot: 0.375rem;',
      '--tint-chip: rgb(157 140 255 / 0.08);',
      '--shadow-card: inset 0 0 0 1px red;',
      '--blur-header: 14px;',
      '--saturate-header: 1.2;',
      '--font-emphasis-weight: 500;',
      '--focus-ring-width: 2px;',
      '--stroke-line: 2px;',
      '--dur-hover: 150ms;',
      '--ease-out: cubic-bezier(0.23, 1, 0.32, 1);',
      '--glide-min: 600ms;',
      '--z-header: 30;',
      '--bp-menu: 67.5rem;',
      '--cq-bento-2: 34rem;',
      '--grad-keycap: linear-gradient(180deg, #1f1a44, #151233);',
      '--light-alpha: 0.09;',
    ]) {
      expect(out.css, line).toContain(line);
    }
  });

  it('emits typography as groups of size, weight, leading, tracking and features', () => {
    expect(out.css).toContain('--font-display-size: clamp(3rem, 6.4vw, 5.75rem);');
    expect(out.css).toContain('--font-display-weight: 600;');
    expect(out.css).toContain('--font-display-leading: 0.96;');
    expect(out.css).toContain('--font-display-tracking: -0.045em;');
    expect(out.css).toContain('--font-body-features: "ss01", "cv11";');
    expect(out.css).not.toContain('--font-body-leading');
  });

  it('exports the breakpoints for TypeScript (media queries cannot use var())', () => {
    expect(out.breakpointsTs).toContain("menu: '67.5rem'");
    expect(out.breakpointsTs).toContain('export const bp');
  });

  it('exports TokenName, readToken and the tokens map', () => {
    expect(out.tokensTs).toContain("'--bg'");
    expect(out.tokensTs).toContain('export type TokenName');
    expect(out.tokensTs).toContain('export function readToken(name: TokenName): string');
    expect(out.tokensTs).toContain('getComputedStyle(document.documentElement)');
    expect(out.tokensTs).toContain('as const satisfies Record<string, TokenName>');
    expect(out.names).toContain('--bg');
  });

  it('is deterministic', () => {
    expect(emitTokens(minimal)).toEqual(out);
  });

  it('rejects a duplicated token name', () => {
    const dup = structuredClone(minimal);
    dup.extensions.alphas.push({ name: 'tint-chip', value: 'red' });
    expect(() => emitTokens(dup)).toThrow(/duplicate/i);
  });

  it('rejects an invalid design.json naming the problem', () => {
    expect(() => emitTokens({ ...minimal, colors: { bg: 12 } })).toThrow(/colors/);
  });

  it('exports bp and cq from their groups, not from name prefixes', () => {
    const tricky = structuredClone(minimal);
    tricky.extensions.scroll.push({ name: 'bp-fake', value: '1rem' });
    const { breakpointsTs } = emitTokens(tricky);
    expect(breakpointsTs).not.toContain('fake');
  });

  it.each([';', '{', '}'])('refuses a value containing %s', (char) => {
    const bad = structuredClone(minimal);
    bad.colors.bg = `#000${char} color: red`;
    expect(() => emitTokens(bad)).toThrow(/break the CSS/);
  });

  it('refuses a px breakpoint', () => {
    const bad = structuredClone(minimal);
    bad.extensions.viewport[0]!.value = '1080px';
    expect(() => emitTokens(bad)).toThrow(/rem/);
  });
});
